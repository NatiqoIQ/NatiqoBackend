"""The seed curriculum: six CEFR levels, declared as data.

Split from :mod:`scripts.seed_content` the same way :mod:`scripts.seed_personas` is split
from :mod:`scripts.seed`: this module is *content*, the other is *machinery*. Writing a
unit here should never mean reading the seeding code.

Two rules make the declaration safe to edit:

**A slug is permanent.** Every row's id is ``uuid5`` of its slug path, so a slug identifies
the row for the life of the database. Renaming a *title* is free; renaming a slug orphans
whatever progress is keyed on the old id. Slugs are therefore descriptive of the topic and
never of the wording.

**A slug is unique within its parent.** The four levels of the path — level, unit, lesson,
question — are joined with ``/`` to derive the id, so two questions sharing a slug inside
one lesson would silently be one row.

The content itself is British English for Iraqi learners. Each question carries its
explanation and may also carry an image and an audio aid: the audio aid pronounces the
taught word or sentence, while a listening item still quotes what the learner hears so the
catalogue stays readable by a client that has not shipped audio.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.core.types import CEFRLevel, QuestionKind, SkillKind


@dataclass(frozen=True)
class SeedQuestion:
    slug: str
    kind: QuestionKind
    skill: SkillKind
    prompt: str
    choices: tuple[str, ...] = ()
    accepted_answers: tuple[str, ...] = ()
    correct_index: int | None = None
    #: A matching item's pairs, each written as ``(item, its match)``. Declared as pairs
    #: rather than as the stored ``"left => right"`` strings so that the two halves of a match
    #: are typed next to each other, and a slipped line cannot silently key one item to
    #: another item's match. The seeder writes them out in the stored form; ``choices`` stays
    #: the bank the learner pairs against, distractors and all.
    matches: tuple[tuple[str, str], ...] = ()
    explanation: str | None = None
    #: Optional pre-attempt visual aid. A question may illustrate the taught word or
    #: sentence without losing its explanation, which stays required.
    image_url: str | None = None
    #: Optional pre-attempt audio aid that pronounces the taught word or sentence. The
    #: counterpart of ``image_url``; the explanation stays required either way.
    audio_url: str | None = None
    #: What the audio aid actually says: the taught word on a vocabulary item, the whole
    #: sentence on a listening one. Declared here rather than derived, because the item's
    #: prompt is an instruction far more often than it is a phrase worth hearing.
    speak: str | None = None
    #: A concrete, searchable phrase for the image aid — ``"a red apple"``, never an
    #: abstract topic word such as ``"food"``. Only the author knows what an item teaches,
    #: and the difference between a picture of a bank and one of a river bank.
    image_query: str | None = None
    points: int = 1


@dataclass(frozen=True)
class SeedLesson:
    slug: str
    title: str
    summary: str
    estimated_minutes: int
    questions: tuple[SeedQuestion, ...] = ()


@dataclass(frozen=True)
class SeedUnit:
    slug: str
    title: str
    description: str | None = None
    lessons: tuple[SeedLesson, ...] = ()


@dataclass(frozen=True)
class SeedLevel:
    slug: str
    code: CEFRLevel
    title: str
    description: str | None = None
    units: tuple[SeedUnit, ...] = ()


# ------------------------------------------------------------------------ A1
# The beginner course, sequenced so that each unit leans on the one before it.
#
# The order is a teaching order rather than a topic list: greetings and introductions
# first, because they are the only thing a learner can use on day one; the verb ``be``
# immediately after, because every other early structure is built on it; then nouns and
# quantity, then place and existence, then the present simple and the modal ``can``.
# Vocabulary arrives with the grammar that makes it sayable — a learner meets family words
# in the unit that teaches possessive adjectives, not in an isolated list.
#
# Three rules keep the level honest, and each is worth stating once:
#
# * **Six skills, not one.** Every unit exercises vocabulary and grammar, and listening,
#   reading, writing and pronunciation each appear somewhere inside it. A unit that only
#   drills words is a word list, not a lesson.
# * **Each kind is used for what it is good at.** Choice questions test recognition,
#   ``fill_blank`` and ``word_bank`` test controlled production, ``ordering`` tests word
#   order and sentence building, ``multi_select`` tests a category rather than a single
#   fact, and ``true_false`` tests a statement the learner has to read or hear first.
# * **The prompt carries the situation.** At A1 the instruction is the hardest thing on
#   the screen, so an item names its context ("A shopkeeper says...") rather than assuming
#   one, and the explanation says why the answer is right rather than restating it.
